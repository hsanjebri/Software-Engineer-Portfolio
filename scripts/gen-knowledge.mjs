// Builds api/_knowledge.js from src/config.ts so the "Ask Hassan" agent only
// knows what the portfolio shows. Runs before every build (npm "prebuild").
import { build } from "esbuild";
import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));

// Bundle config + case studies into one module and import it from memory.
const out = await build({
  stdin: {
    contents: `export { config } from "./src/config.ts"; export { caseStudies } from "./src/data/caseStudies.ts";`,
    resolveDir: root,
    loader: "ts",
  },
  bundle: true,
  format: "esm",
  platform: "node",
  write: false,
});
const { config, caseStudies } = await import(
  `data:text/javascript;base64,${Buffer.from(out.outputFiles[0].text).toString("base64")}`
);

const { developer, social, about, experiences, projects, certificates, contact, skills, proof } = config;
const lines = [];
const push = (...l) => lines.push(...l);

push(
  `# ${developer.fullName}`,
  `${developer.title}, based in ${social.location}.`,
  developer.description,
  "",
  "## About",
  about.description,
  ...about.stats.map((s) => `- ${s.value}: ${s.label}`),
  "",
  "## Contact",
  `- Email: ${contact.email}`,
  `- GitHub: ${contact.github}`,
  `- LinkedIn: ${contact.linkedin}`,
  `- X / Twitter: ${contact.twitter}`,
  "",
  "## Experience and education (newest last)"
);
for (const e of experiences) {
  push(
    "",
    `### ${e.position} at ${e.company} (${e.period}, ${e.location})`,
    e.description,
    ...e.responsibilities.map((r) => `- ${r}`),
    `Tech: ${e.technologies.join(", ")}`
  );
}

push("", "## Projects (newest first)");
for (const p of projects) {
  push(
    "",
    `### ${p.title} [${p.category}]`,
    p.link ? `Link: ${p.link}` : "No public link.",
    `Tech: ${p.technologies}`,
    // Projects with a case study are described in full below; skip the duplicate.
    caseStudies.some((cs) => cs.projectId === p.id) ? "Full story in the case study below." : p.description
  );
}

push("", "## Case studies (in depth, on the site at /work/<slug>)");
for (const cs of caseStudies) {
  const p = projects.find((x) => x.id === cs.projectId);
  push(
    "",
    `### ${p ? p.title : cs.slug}: ${cs.tagline} (page: /work/${cs.slug})`,
    `Role: ${cs.role}. Year: ${cs.year}. Status: ${cs.status}.`,
    ...cs.results.map((r) => `- ${r.value} ${r.label}`),
    "Problem: " + cs.problem.join(" "),
    "What he built: " + cs.built.join(" "),
    "Architecture: " + cs.diagram.map((c) => `${c.title} (${c.nodes.map((n) => n.label).join(", ")})`).join(" -> "),
    ...cs.hard.map((h) => `- Hard part, ${h.title}: ${h.body}`)
  );
}

push("", "## In production", ...proof.stats.map((s) => `- ${s.value} ${s.label}`));
for (const t of proof.testimonials) push(`- Client quote from ${t.name} (${t.role}): "${t.quote}"`);

push("", "## Certificates");
for (const c of certificates) {
  const scores = c.scores
    ? ` (listening ${c.scores.listening}, reading ${c.scores.reading}, writing ${c.scores.writing}, speaking ${c.scores.speaking})`
    : "";
  push(`- ${c.title}, ${c.issuer}, ${c.date}${scores}`);
}

push("", "## Skills");
for (const s of Object.values(skills)) {
  push(`- ${s.title}: ${s.details} Tools: ${s.tools.join(", ")}`);
}

const file = `// Generated by scripts/gen-knowledge.mjs from src/config.ts. Do not edit by hand.
export const KNOWLEDGE = ${JSON.stringify(lines.join("\n"))};
`;
await writeFile(`${root}api/_knowledge.js`, file);
console.log(`api/_knowledge.js: ${lines.length} lines`);
